import AppKit
import Foundation
import ImageIO
import UniformTypeIdentifiers

// Reproduce the family's cover layout with Naberius's existing, unaltered seal.
let root = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
let output = root.appendingPathComponent("docs/assets/brand", isDirectory: true)
try FileManager.default.createDirectory(at: output, withIntermediateDirectories: true)
let source = try String(contentsOf: root.appendingPathComponent("Resources/Brand/symbol-dark.svg"), encoding: .utf8)
let expectedPath = "M 30 24 V 76 M 20 43 H 58 M 20 57 H 58 M 55 24 C 79 31 79 41 62 50 C 79 59 79 69 55 76"
precondition(source.contains("d=\"\(expectedPath)\""), "The brand geometry changed; update the cover renderer before regenerating.")
let navy = NSColor(srgbRed: 17/255, green: 27/255, blue: 38/255, alpha: 1)
let ivory = NSColor(srgbRed: 232/255, green: 230/255, blue: 217/255, alpha: 1)
let teal = NSColor(srgbRed: 0.50, green: 0.70, blue: 0.77, alpha: 1)
let size = NSSize(width: 1600, height: 800)
let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 1600, pixelsHigh: 800, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
NSGraphicsContext.saveGraphicsState()
NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
navy.setFill()
NSRect(origin: .zero, size: size).fill()
func text(_ value: String, x: CGFloat, y: CGFloat, size: CGFloat, weight: NSFont.Weight, color: NSColor, tracking: CGFloat = 0) {
    (value as NSString).draw(at: NSPoint(x: x, y: y), withAttributes: [.font: NSFont.systemFont(ofSize: size, weight: weight), .foregroundColor: color, .kern: tracking])
}
let cg = NSGraphicsContext.current!.cgContext
cg.saveGState()
cg.translateBy(x: 975, y: 695)
cg.scaleBy(x: 500/64, y: -500/64)
cg.translateBy(x: -16, y: -18)
let mark = NSBezierPath()
mark.move(to: NSPoint(x: 30, y: 24)); mark.line(to: NSPoint(x: 30, y: 76))
for y in [43.0, 57] {
    mark.move(to: NSPoint(x: 20, y: y)); mark.line(to: NSPoint(x: 58, y: y))
}
mark.move(to: NSPoint(x: 55, y: 24))
mark.curve(to: NSPoint(x: 62, y: 50), controlPoint1: NSPoint(x: 79, y: 31), controlPoint2: NSPoint(x: 79, y: 41))
mark.curve(to: NSPoint(x: 55, y: 76), controlPoint1: NSPoint(x: 79, y: 59), controlPoint2: NSPoint(x: 79, y: 69))
mark.lineCapStyle = .round
mark.lineJoinStyle = .round
mark.lineWidth = 3.2
teal.setStroke(); mark.stroke()
cg.restoreGState()
text("NABERIUS", x: 82, y: 578, size: 81, weight: .semibold, color: ivory, tracking: 8)
text("Escritura visual.", x: 85, y: 414, size: 48, weight: .medium, color: ivory)
text("Composición precisa.", x: 85, y: 351, size: 48, weight: .medium, color: ivory)
text("Escribe · estructura · compón", x: 87, y: 279, size: 25, weight: .regular, color: teal)
let rule = NSBezierPath()
rule.move(to: NSPoint(x: 86, y: 191)); rule.line(to: NSPoint(x: 1514, y: 191)); rule.lineWidth = 1
ivory.withAlphaComponent(0.18).setStroke(); rule.stroke()
text("NATIVO PARA macOS", x: 87, y: 128, size: 16, weight: .semibold, color: ivory, tracking: 2)
text("SwiftUI  /  Apple Silicon  /  Procesamiento local", x: 87, y: 86, size: 20, weight: .regular, color: teal)
text("Creado por Sebastián Pastén F.", x: 1100, y: 90, size: 18, weight: .regular, color: ivory)
NSGraphicsContext.restoreGraphicsState()
let destination = CGImageDestinationCreateWithURL(output.appendingPathComponent("cover.png") as CFURL, UTType.png.identifier as CFString, 1, nil)!
let origin = "Naberius geometric cover. Generated by script/make_cover.swift from the original Naberius seal. Layout reference: METATRON family cover. Native AppKit rendering, 1600x800."
CGImageDestinationAddImage(destination, rep.cgImage!, [kCGImagePropertyPNGDictionary: [kCGImagePropertyPNGDescription: origin]] as CFDictionary)
guard CGImageDestinationFinalize(destination) else { throw NSError(domain: "NaberiusCover", code: 1) }
print(output.appendingPathComponent("cover.png").path)
