import Foundation

public enum LaTeX {
    public static func escape(_ text: String) -> String {
        text.map { c in switch c {
        case "\\": "\\textbackslash{}"; case "{": "\\{"; case "}": "\\}"; case "$": "\\$"; case "&": "\\&"; case "%": "\\%"; case "#": "\\#"; case "_": "\\_"; case "~": "\\textasciitilde{}"; case "^": "\\textasciicircum{}"; case "\u{fffc}": ""; default: String(c)
        }}.joined()
    }
    public static func mathText(_ text: String) -> String {
        let greek: [Character:String] = ["α":"\\alpha ","β":"\\beta ","γ":"\\gamma ","δ":"\\delta ","ε":"\\epsilon ","θ":"\\theta ","λ":"\\lambda ","μ":"\\mu ","π":"\\pi ","σ":"\\sigma ","φ":"\\phi ","ω":"\\omega ","∞":"\\infty ","×":"\\times ","÷":"\\div ","≤":"\\leq ","≥":"\\geq ","≠":"\\neq "]
        return text.map { c in if let g = greek[c] { g } else if c.isLetter || c.isNumber || "+-=().,[] ".contains(c) { String(c) } else { "\\text{\(escape(String(c)))}" } }.joined()
    }
    public static func equation(_ m: MathExpression) -> String {
        let a = mathText(m.first), b = mathText(m.second), lo = mathText(m.lower), hi = mathText(m.upper)
        return switch m.operation {
        case .text: a; case .fraction: "\\frac{\(a)}{\(b)}"; case .root: "\\sqrt{\(a)}"
        case .power: "{\(a)}^{\(b)}"; case .subscripted: "{\(a)}_{\(b)}"
        case .sum: "\\sum_{\(lo)}^{\(hi)} \(a)"; case .integral: "\\int_{\(lo)}^{\(hi)} \(a)\\,d\(b)"
        }
    }
    /// Typographic logos are derived display, while the document keeps the original text.
    public static func bodyText(_ text: String) -> String {
        let ns = text as NSString
        var result = "", offset = 0
        for logo in DocumentTypography.logos(in: text) {
            result += escape(ns.substring(with: NSRange(location: offset, length: logo.range.location-offset)))
            result += logo.isLaTeX ? "\\LaTeX{}" : "\\TeX{}"
            offset = NSMaxRange(logo.range)
        }
        return result + escape(ns.substring(from: offset))
    }
    static func fontSetup(_ font: String) -> [String] {
        if DocumentTypography.safeFont(font) == DocumentTypography.defaultFont {
            return ["\\usepackage{fontspec}", "\\defaultfontfeatures{Ligatures=TeX}", "\\setmainfont[Path=fonts/,BoldFont=lmroman10-bold.otf,ItalicFont=lmroman10-italic.otf,BoldItalicFont=lmroman10-bolditalic.otf]{lmroman10-regular.otf}"]
        }
        return ["\\usepackage{fontspec}", "\\setmainfont{\(DocumentTypography.safeFont(font))}"]
    }
    public static func source(_ d: NabDocument, citations: CitationOutput = CitationOutput()) -> String {
        if let package=d.template.package {return package.source(d,citations:citations)}
        let t = d.template, m = d.metadata, layout = t.effectiveLayout
        let kind = layout.documentClass
        let paper = ["letterpaper", "legalpaper"].contains(t.paper) ? t.paper : "a4paper"
        let classSize = [10, 11, 12].min(by: { abs(Double($0)-t.fontSize) < abs(Double($1)-t.fontSize) }) ?? 12
        let options = "\(classSize)pt,\(paper)" + (kind.hasChapters ? ",oneside,openany" : "")
        let spanish = m.language.hasPrefix("es")
        var lines = ["% Generated by Naberius. Content is escaped; shell escape is disabled.", "\\documentclass[\(options)]{\(kind.rawValue)}"]
        lines += fontSetup(t.font)
        if kind == .letter {lines.append("\\makeatletter\\@ifundefined{c@table}{\\newcounter{table}}{}\\providecommand{\\tablename}{Tabla}\\providecommand{\\fnum@table}{\\tablename~\\thetable}\\makeatother")}
        lines += ["\\usepackage[\(spanish ? "spanish" : "english")]{babel}", "\\usepackage[margin=\(t.marginMM)mm,headheight=16pt]{geometry}", "\\usepackage{graphicx,amsmath,amssymb,tabularx,booktabs,longtable}", "\\usepackage{fancyhdr}", "\\usepackage[unicode,hidelinks]{hyperref}", "\\hypersetup{pdftitle={\(escape(m.title))},pdfauthor={\(escape(m.authors))},pdfkeywords={\(escape(m.keywords))}}"]
        if kind != .letter {
            lines += ["\\addto\\captions\(spanish ? "spanish" : "english"){\\renewcommand{\\figurename}{\(spanish ? "Figura" : "Figure")}\\renewcommand{\\tablename}{\(spanish ? "Tabla" : "Table")}\\renewcommand{\\contentsname}{\(spanish ? "Índice" : "Contents")}}", "\\setcounter{secnumdepth}{\(t.numberedHeadings ? (kind.hasChapters ? 3 : 4) : -1)}"]
        }
        if kind.hasChapters {
            // Semantic object numbers are global and do not reset at each chapter.
            lines += ["\\counterwithout{figure}{chapter}", "\\counterwithout{table}{chapter}", "\\counterwithout{equation}{chapter}"]
        }
        let pageFooter = [bodyText(layout.footer), layout.pageNumbers ? "\\thepage" : ""].filter { !$0.isEmpty }.joined(separator: "\\quad ")
        let pageStyle = "\\fancyhf{}\\fancyhead[L]{\\small \(bodyText(layout.header))}\\fancyfoot[C]{\\small \(pageFooter)}\\renewcommand{\\headrulewidth}{\(layout.header.isEmpty ? "0" : "0.4")pt}"
        lines += ["\\pagestyle{fancy}", pageStyle, "\\fancypagestyle{plain}{\(pageStyle)}", "\\linespread{\(t.lineSpacing)}", "\\setlength{\\parindent}{\(layout.paragraphIndentMM)mm}", "\\setlength{\\parskip}{\(layout.paragraphSpacingPT)pt}"]
        if kind == .letter { lines += ["\\signature{\(escape(m.authors))}", "\\address{\(escape(m.institution))}", "\\date{\(escape(m.date))}"] }
        lines.append("\\begin{document}")
        if t.cover && kind != .letter {
            lines += ["\\begin{titlepage}\\centering\\vspace*{3cm}", "{\\LARGE\\bfseries \(bodyText(m.title))\\par}", "\\vspace{1cm}\(bodyText(m.subtitle))\\par", "\\vfill \(bodyText(m.authors))\\par \(bodyText(m.institution))\\par \(bodyText(m.date))", "\\end{titlepage}"]
        }
        if kind == .letter { lines += ["\\begin{letter}{\(bodyText(layout.recipient))}", "\\opening{\(bodyText(layout.opening))}", "\\thispagestyle{fancy}"] }
        if !m.abstract.isEmpty {
            if kind == .article { lines += ["\\begin{abstract}\(bodyText(m.abstract))\\end{abstract}"] }
            else { lines += [kind.hasChapters ? "\\chapter*{\(spanish ? "Resumen" : "Abstract")}" : "{\\large\\bfseries \(spanish ? "Resumen" : "Abstract")\\par}", bodyText(m.abstract)] }
        }
        lines.append("\\fontsize{\(t.fontSize)}{\(t.fontSize*1.2)}\\selectfont")
        lines.append(body(d,citations:citations))
        if m.bibliography && !citations.bibliography.isEmpty {
            lines.append(kind.hasChapters ? "\\chapter*{Referencias}" : (kind == .letter ? "{\\large\\bfseries Referencias\\par}" : "\\section*{Referencias}"))
            lines += citations.bibliography.map { "\\noindent \(bodyText($0))\\par\\medskip" }
        }
        if kind == .letter { lines += ["\\closing{\(bodyText(layout.closing))}", "\\end{letter}"] }
        lines.append("\\end{document}")
        return lines.joined(separator: "\n")
    }
    static func body(_ d:NabDocument,citations:CitationOutput,omitTitle:Bool=false)->String {
        let kind=d.template.effectiveLayout.documentClass
        var lines:[String]=[]
        var activeList: String?
        var inAppendices = false
        for block in d.blocks {
            if omitTitle && (block.style == .title || block.style == .subtitle) {continue}
            let list = block.style == .bullet ? "itemize" : (block.style == .numbered ? "enumerate" : nil)
            if list != activeList {
                if let activeList { lines.append("\\end{\(activeList)}") }
                if let list { lines.append("\\begin{\(list)}") }
                activeList = list
            }
            let text = block.semanticRuns.map { run -> String in
                if let id = run.nodeID, let n = d.nodes.first(where: { $0.id == id }) { return node(n, in: d, citations: citations) }
                var value = bodyText(run.text)
                if run.bold { value = "\\textbf{\(value)}" }; if run.italic { value = "\\textit{\(value)}" }
                if run.script > 0 { value = "\\textsuperscript{\(value)}" }; if run.script < 0 { value = "\\textsubscript{\(value)}" }
                if let link = run.link, let url = URL(string: link), ["https", "http", "mailto"].contains(url.scheme?.lowercased() ?? "") { value = "\\href{\(escape(link))}{\(value)}" }
                return value
            }.joined()
            if block.style == .appendix && !inAppendices && kind != .letter {
                lines.append("\\appendix");inAppendices=true
            }
            let label = "\\label{b\(block.id.uuidString)}"
            let rendered: String
            if let level = block.style.headingLevel {
                if kind == .letter { rendered = "\\par\\medskip\\phantomsection\(label){\\large\\bfseries \(text)\\par}" }
                else {
                    let commands = kind.hasChapters ? ["chapter", "section", "subsection", "subsubsection"] : ["section", "subsection", "subsubsection", "paragraph"]
                    rendered = "\\\(commands[level-1]){\(text)}\(label)"
                }
            } else {
                rendered = switch block.style {
                case .title: "{\\LARGE\\bfseries \(text)\\par}"
                case .subtitle: "{\\large \(text)\\par}"
                case .quote: "\\begin{quote}\(text)\\end{quote}"
                case .bullet, .numbered: "\\item \(text)"
                case .caption: "{\\small \(text)\\par}"
                case .pageBreak: "\\newpage"
                default: text
                }
            }
            lines.append(rendered+"\n")
        }
        if let activeList { lines.append("\\end{\(activeList)}") }
        return lines.joined(separator:"\n")
    }
    private static func node(_ n: AcademicNode, in d: NabDocument, citations: CitationOutput) -> String {
        let label = "\\label{n\(n.id.uuidString)}"
        let note = [n.note,n.source.isEmpty ? "" : "Fuente: "+n.source].filter{!$0.isEmpty}.map(escape).joined(separator:"\\par ")
        switch n.kind {
        case .figure:
            guard let asset = d.assets.first(where: { $0.id == n.assetID }) else { return "[Imagen no encontrada]" }
            let file = asset.id.uuidString+"."+assetExtension(asset)
            let alignment = n.alignment == "left" ? "\\raggedright" : (n.alignment == "right" ? "\\raggedleft" : "\\centering")
            let content = "\\includegraphics[width=\(min(n.width/520,1))\\linewidth]{assets/\(file)}"
            if d.template.effectiveLayout.documentClass == .letter {
                return "\\par\\medskip\\phantomsection\(label){\(alignment)\(content)\\par\\small Figura \(d.number(of:n.id) ?? 0). \(bodyText(n.caption))\\par\(note)\\par}"
            }
            return "\\begin{figure}[htbp]\(alignment)\n\(content)\n\\caption{\(bodyText(n.caption))}\(label)\n{\\small \(note)}\n\\end{figure}"
        case .table: return table(n,in:d)
        case .equation:
            let eq = equation(n.math)
            if n.inline { return "$\(eq)$" }
            return n.numbered ? "\\begin{equation}\(eq)\(label)\\end{equation}" : "\\[\(eq)\\]"
        case .citation:
            if let package=d.template.package {return package.citation(n,in:d)}
            return escape(citations.citations[n.id] ?? "[Referencia no encontrada]")
        case .crossReference:
            guard let target = n.targetID else { return "[Destino no encontrado]" }
            if d.blocks.contains(where:{$0.id==target && $0.style.headingLevel != nil}) { return "\\hyperref[b\(target.uuidString)]{\(escape(d.crossReference(target)))}" }
            guard d.number(of:target) != nil else { return "[Destino no encontrado]" }
            return "\\hyperref[n\(target.uuidString)]{\(escape(d.crossReference(target)))}"
        case .footnote: return "\\footnote{\(escape(n.note))}"
        case .contents: return d.template.effectiveLayout.documentClass == .letter ? "" : "\\tableofcontents"
        case .separator: return "\\par\\medskip\\noindent\\rule{\\linewidth}{0.4pt}\\par\\medskip"
        }
    }
    private static func tableCell(_ value:String)->String {
        value.split(separator:" ",omittingEmptySubsequences:false).map {word in
            let chars=Array(word)
            if chars.count>40 {
                return stride(from:0,to:chars.count,by:24).map {start in bodyText(String(chars[start..<min(start+24,chars.count)]))}.joined(separator:"\\allowbreak{}")
            }
            return bodyText(String(word))
        }.joined(separator:" ").replacingOccurrences(of:"\n",with:"\\newline{}")
    }
    private static func table(_ n:AcademicNode,in d:NabDocument)->String {
        let columns=max(1,n.rows.first?.count ?? 1),grid=n.tableStyle=="Cuadrícula",academic=n.tableStyle=="Académico"
        let multipage=n.rows.count>12 || n.rows.flatMap{$0}.reduce(0){$0+$1.count}>1200
        let label="\\label{n\(n.id.uuidString)}"
        let notes=[n.note,n.source.isEmpty ? "" : "Fuente: "+n.source].filter{!$0.isEmpty}.map(bodyText).joined(separator:"\\par ")
        let column=multipage ? ">{\\raggedright\\arraybackslash\\hspace{0pt}}p{\\dimexpr(\\linewidth-\(2*columns)\\tabcolsep-\(grid ? columns+1 : 0)\\arrayrulewidth)/\(columns)\\relax}" : ">{\\raggedright\\arraybackslash}X"
        let spec=grid ? "|"+Array(repeating:column,count:columns).joined(separator:"|")+"|" : String(repeating:column,count:columns)
        func row(_ values:[String],header:Bool)->String {
            values.map{header ? "\\textbf{\(tableCell($0))}" : tableCell($0)}.joined(separator:" & ")+" \\\\"+(grid ? " \\hline" : "")
        }
        let top=grid ? "\\hline" : (academic ? "\\toprule" : "")
        let middle=academic && n.header ? "\\midrule" : ""
        let bottom=academic ? "\\bottomrule" : ""
        if multipage {
            let head=n.header ? row(n.rows[0],header:true)+middle : ""
            let body=(n.header ? Array(n.rows.dropFirst()) : n.rows).map{row($0,header:false)}.joined(separator:"\n")
            let continuation=d.metadata.language.hasPrefix("es") ? "continuación" : "continued"
            let longTable="\\begin{longtable}{\(spec)}\n\\caption{\(bodyText(n.caption))}\(label)\\\\\n\(top)\n\(head)\n\\endfirsthead\n\\multicolumn{\(columns)}{l}{\\small \\tablename~\\thetable~(\(continuation))}\\\\\n\(top)\n\(head)\n\\endhead\n\(bottom)\\endfoot\n\(bottom)\\endlastfoot\n\(body)\n\\end{longtable}\n{\\small \(notes)\\par}"
            guard d.template.package != nil else{return longTable}
            // Longtable cannot run in two columns. Preserve the class layout and split
            // large tables into bounded full-width floats with repeated column headings.
            let values=n.header ? Array(n.rows.dropFirst()) : n.rows
            let floatSpec=grid ? "|"+Array(repeating:">{\\raggedright\\arraybackslash}X",count:columns).joined(separator:"|")+"|" : String(repeating:">{\\raggedright\\arraybackslash}X",count:columns)
            let parts=stride(from:0,to:values.count,by:12).enumerated().map {part,start in
                let body=values[start..<min(start+12,values.count)].map{row($0,header:false)}.joined(separator:"\n")
                let caption=bodyText(n.caption)+(part==0 ? "" : " ("+continuation+")")
                let counter=part==0 ? "" : "\\addtocounter{table}{-1}"
                return "\\begin{table*}[tp]\\centering\(counter)\\caption{\(caption)}\(part==0 ? label : "")\n\\begin{tabularx}{\\linewidth}{\(floatSpec)}\(top)\n\(head)\n\(body)\n\(bottom)\\end{tabularx}\\par{\\small \(notes)}\\end{table*}"
            }.joined(separator:"\n")
            return "\\makeatletter\n\\if@twocolumn\n\(parts)\n\\else\n\(longTable)\n\\fi\n\\makeatother"
        }
        let rows=n.rows.enumerated().map{index,values in row(values,header:n.header && index==0)+(index==0 ? middle : "")}.joined(separator:"\n")
        let content="\\begin{tabularx}{\\linewidth}{\(spec)}\(top)\n\(rows)\n\(bottom)\\end{tabularx}"
        if d.template.effectiveLayout.documentClass == .letter {
            return "\\par\\medskip\\phantomsection\(label){\\small Tabla \(d.number(of:n.id) ?? 0). \(bodyText(n.caption))\\par}\n\(content)\\par{\\small \(notes)}"
        }
        return "\\begin{table}[htbp]\\centering\\caption{\(bodyText(n.caption))}\(label)\n\(content)\\par{\\small \(notes)}\\end{table}"
    }
    public static func assetExtension(_ a: Asset) -> String { a.mediaType == "image/png" ? "png" : (a.mediaType == "image/jpeg" ? "jpg" : "pdf") }
    public static func writeFonts(at url: URL) throws {
        let target = url.appendingPathComponent("fonts")
        try FileManager.default.createDirectory(at: target, withIntermediateDirectories: true)
        for file in DocumentTypography.fontFiles + ["GUST-FONT-LICENSE.TXT", "README-Latin-Modern.TXT", "MANIFEST-Latin-Modern.TXT"] {
            try Data(contentsOf: DocumentTypography.fontURL(file)).write(to: target.appendingPathComponent(file), options: .atomic)
        }
    }
    @discardableResult public static func writeProject(_ d: NabDocument, at url: URL) throws -> URL {
        try NabArchive.validate(d)
        let fm = FileManager.default; try fm.createDirectory(at:url,withIntermediateDirectories:true)
        let main=try d.template.package?.materialize(at:url) ?? url.appendingPathComponent("main.tex")
        let working=main.deletingLastPathComponent()
        let assets = working.appendingPathComponent("assets"); try fm.createDirectory(at:assets,withIntermediateDirectories:true)
        if d.template.package==nil {try writeFonts(at:working)}
        let cites = try Bibliography.render(d)
        try source(d,citations:cites).write(to:main,atomically:true,encoding:.utf8)
        try Bibliography.cslJSON(d.references).write(to:url.appendingPathComponent("references.json"),options:.atomic)
        try Bibliography.bibTeX(d.references).write(to:url.appendingPathComponent("references.bib"),atomically:true,encoding:.utf8)
        if let package=d.template.package {try package.bibliography(d.references).write(to:working.appendingPathComponent("naberius-references.bib"),atomically:true,encoding:.utf8)}
        for a in d.assets { try a.data.write(to:assets.appendingPathComponent(a.id.uuidString+"."+assetExtension(a)),options:.atomic) }
        let instructions:String
        if let package=d.template.package {
            let relative=String(main.path.dropFirst(url.path.count)).trimmingCharacters(in:CharacterSet(charactersIn:"/"))
            instructions="""
            Proyecto editorial generado por Naberius.
            Entrada generada: \(relative)
            Entrada original: \(package.plan.mainFile)
            Clase: \(package.plan.documentClass) [\(package.plan.options.joined(separator:", "))]
            Bibliografía: \(package.plan.bibliographyBackend). naberius-references.bib contiene los datos del documento.
            Ejecutar desde la carpeta de la entrada. Tectonic resuelve BibTeX automáticamente; un flujo TeX Live debe ejecutar LaTeX, BibTeX y LaTeX dos veces.
            Los archivos originales se conservan en \(package.originalDirectoryName)/ y los recursos editoriales mantienen sus rutas. El PDF de referencia no es el PDF generado.
            La clase controla fuentes, márgenes y estilos. No activar shell-escape. Las licencias del paquete original pertenecen a sus titulares.
            """
        } else {instructions="Compilar main.tex con XeLaTeX o Tectonic. Citas y bibliografía se resuelven con CSL antes de exportar. No se requiere shell-escape.\n"}
        try instructions.write(to:url.appendingPathComponent("README.txt"),atomically:true,encoding:.utf8)
        return main
    }
}

public struct CompositionFailure:LocalizedError,Sendable {
    public let summary:String
    public let log:String
    public let engine:URL
    public var errorDescription:String? {summary}
}
public struct Compilation: Sendable {
    public let pdf: URL
    public let log: String
    public let engine: URL
    public let completedAt: Date
    public let elapsed: TimeInterval
}
public enum Composer {
    public static func detectedEngine(custom: String = "") -> URL? {
        let candidates = [custom,"/opt/homebrew/bin/tectonic","/usr/local/bin/tectonic","/Applications/ChatGPT.app/Contents/Resources/tectonic/tectonic"]
        return candidates.first { !$0.isEmpty && FileManager.default.isExecutableFile(atPath:$0) }.map { URL(fileURLWithPath:$0) }
    }
    @concurrent public static func compile(_ d: NabDocument, engine: URL, allowNetwork: Bool = false) async throws -> Compilation {
        try Task.checkCancellation()
        let work = FileManager.default.temporaryDirectory.appendingPathComponent("Naberius-"+UUID().uuidString)
        let main=try LaTeX.writeProject(d,at:work)
        if let package=d.template.package,package.plan.requiredEngine != "tectonic" || package.plan.bibliographyBackend=="biber" {throw NabError.invalid(L10n.text("El paquete requiere LuaLaTeX o Biber, que no están disponibles con este motor. Sus archivos y configuración se conservan."))}
        return try await run(engine:engine,work:main.deletingLastPathComponent(),allowNetwork:allowNetwork,isolationRoot:d.template.package==nil ? nil : work)
    }
    @concurrent public static func compileMath(_ math: MathExpression, engine: URL, allowNetwork: Bool = false) async throws -> Compilation {
        let work = FileManager.default.temporaryDirectory.appendingPathComponent("Naberius-Math-"+UUID().uuidString)
        try FileManager.default.createDirectory(at: work, withIntermediateDirectories: true)
        try LaTeX.writeFonts(at: work)
        let source = (["\\documentclass{article}"] + LaTeX.fontSetup(DocumentTypography.defaultFont) + ["\\usepackage{amsmath,amssymb}", "\\pagestyle{empty}", "\\begin{document}", "\\["+LaTeX.equation(math)+"\\]", "\\end{document}"]).joined(separator: "\n")
        try source.write(to: work.appendingPathComponent("main.tex"), atomically: true, encoding: .utf8)
        return try await run(engine: engine, work: work, allowNetwork: allowNetwork)
    }
    static func failureSummary(log:String,allowNetwork:Bool)->String {
        let missingCache=log.lowercased().contains("not in cache") || log.contains("only-cached") || (!allowNetwork && (log.contains("not loadable: Metric") || log.contains("not found") && log.contains("LaTeX Error: File")))
        return missingCache ? L10n.text("Faltan paquetes o fuentes de LaTeX en la caché local. Prepáralos desde Configuración → Composición con «Componer y permitir descarga de paquetes». Puedes seguir escribiendo y guardando.") : L10n.text("LaTeX no pudo componer este PDF. Puedes seguir escribiendo y guardando; revisa los detalles de composición.")
    }
    @concurrent private static func run(engine: URL, work: URL, allowNetwork: Bool,isolationRoot:URL?=nil) async throws -> Compilation {
        try Task.checkCancellation()
        let started = Date()
        let logURL = work.appendingPathComponent("composition.log")
        FileManager.default.createFile(atPath:logURL.path,contents:nil)
        let handle = try FileHandle(forWritingTo:logURL); defer { try? handle.close() }
        let p = Process(); p.executableURL = engine; p.currentDirectoryURL = work
        p.arguments = ["-X","compile","--untrusted","--keep-logs","--outdir",work.path] + (allowNetwork ? [] : ["--only-cached"]) + [work.appendingPathComponent("main.tex").path]
        if let isolationRoot {
            guard FileManager.default.isExecutableFile(atPath:"/usr/bin/sandbox-exec") else {throw NabError.invalid(L10n.text("No se pudo aislar el compilador de la plantilla. El paquete se conserva sin ejecutar."))}
            p.executableURL=URL(fileURLWithPath:"/usr/bin/sandbox-exec")
            let profile=TemplateSandbox.profile(engine:engine,root:isolationRoot,allowNetwork:allowNetwork)
            try profile.write(to:isolationRoot.appendingPathComponent("compiler.sb"),atomically:true,encoding:.utf8)
            p.arguments=["-p",profile,engine.path]+(p.arguments ?? [])
        }
        var env = ProcessInfo.processInfo.environment; env["TECTONIC_UNTRUSTED_MODE"] = "1"; env["openin_any"] = "p"; env["openout_any"] = "p"
        if let isolationRoot {
            let temporary=isolationRoot.appendingPathComponent("engine-temporary")
            try FileManager.default.createDirectory(at:temporary,withIntermediateDirectories:true)
            env["TMPDIR"]=temporary.path+"/"
        }
        p.environment = env
        p.standardOutput = handle; p.standardError = handle
        return try await withTaskCancellationHandler {
            try p.run()
            let deadline = Date().addingTimeInterval(allowNetwork ? 900 : 90)
            while p.isRunning {
                if Task.isCancelled || Date() > deadline { p.terminate(); p.waitUntilExit(); throw NabError.cancelled }
                try await Task.sleep(for:.milliseconds(100))
            }
            let log = (try? String(contentsOf:logURL,encoding:.utf8)) ?? ""
            let pdf = work.appendingPathComponent("main.pdf")
            guard p.terminationStatus == 0, FileManager.default.fileExists(atPath:pdf.path) else { throw CompositionFailure(summary:failureSummary(log:log,allowNetwork:allowNetwork),log:String(log.suffix(40000)),engine:engine) }
            return Compilation(pdf:pdf,log:log,engine:engine,completedAt:Date(),elapsed:Date().timeIntervalSince(started))
        } onCancel: { if p.isRunning { p.terminate() } }
    }
}
